// Export the project's installed Lucide artwork for the native screenshot renderer.
// Lucide: ISC, see crates/airsnip/assets/icons/lucide/LICENSE.
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
const require = createRequire(import.meta.url);
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const lucide = require("lucide-react");
const root = fileURLToPath(new URL("../crates/airsnip/assets/icons/lucide/", import.meta.url));
const icons = {
  rect: "RectangleHorizontal", arrow: "MoveUpRight", text: "Type", highlight: "Highlighter",
  blur: "Blend", glow: "Flashlight", number: "ListOrdered", line: "Minus", ellipse: "Circle",
  freehand: "Pencil", fill: "PaintBucket", undo: "Undo2", redo: "Redo2", pin: "Pin",
  longshot: "ScanLine", ocr: "ScanText", copy: "Copy", save: "Save", bold: "Bold",
  italic: "Italic", minus: "Minus", plus: "Plus", check: "Check", cross: "X", delete: "Trash2",
};
function pathOf(tag, attrs) {
  const a = Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
  if (tag === "path") return a.d;
  if (tag === "line") return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
  if (tag === "polyline" || tag === "polygon") return `M${a.points}${tag === "polygon" ? "Z" : ""}`;
  if (tag === "circle") return `M${+a.cx - +a.r} ${a.cy}a${a.r} ${a.r} 0 1 0 ${+a.r * 2} 0a${a.r} ${a.r} 0 1 0 ${-a.r * 2} 0`;
  if (tag === "rect") {
    const [x, y, w, h, r] = [a.x, a.y, a.width, a.height, a.rx ?? 0].map(Number);
    return `M${x + r} ${y}H${x + w - r}Q${x + w} ${y} ${x + w} ${y + r}V${y + h - r}Q${x + w} ${y + h} ${x + w - r} ${y + h}H${x + r}Q${x} ${y + h} ${x} ${y + h - r}V${y + r}Q${x} ${y} ${x + r} ${y}Z`;
  }
  throw new Error(`Unsupported Lucide primitive: ${tag}`);
}
mkdirSync(root, { recursive: true });
for (const [name, component] of Object.entries(icons)) {
  const svg = renderToStaticMarkup(createElement(lucide[component]));
  const paths = [...svg.matchAll(/<(path|line|polyline|polygon|circle|rect)\b([^>]*?)\/?\s*>/g)]
    .map((m) => `<path d="${pathOf(m[1], m[2])}"/>`).join("");
  if (!paths) throw new Error(`Empty icon: ${component}`);
  writeFileSync(join(root, `${name}.svg`), `<!-- Lucide ${component}; ISC; generated by scripts/sync-screenshot-icons.mjs -->\n<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.25" stroke-linecap="round" stroke-linejoin="round">${paths}</svg>\n`);
}
const entry = require.resolve("lucide-react");
const license = join(entry, "../../../LICENSE");
writeFileSync(join(root, "LICENSE"), readFileSync(license));
console.log(`Exported ${Object.keys(icons).length} Lucide screenshot icons`);
