const voidTags = new Set(["path", "circle", "rect", "line", "polyline", "polygon", "ellipse"]);

function readIcon(name) {
  const source = readFileSync(join(iconDir, `${name}.mjs`), "utf8");
  const start = source.indexOf("__iconNode = [");
  if (start < 0) {
    // An alias re-exports another icon's module.
    const alias = source.match(/from '\.\/([a-z0-9-]+)\.mjs'/);
    if (!alias) throw new Error(`no icon node in ${name}`);
    return readIcon(alias[1]);
  }
  const end = source.indexOf("];", start);
  const body = source.slice(start + "__iconNode = ".length, end + 1);
  // The node array is plain JS literals: evaluate it in isolation.
  const nodes = Function(`return ${body};`)();
  return nodes
    .map(([tag, attrs]) => {
      const attributes = Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => `${key}="${value}"`)
        .join(" ");
      return voidTags.has(tag) ? `<${tag} ${attributes}/>` : `<${tag} ${attributes}></${tag}>`;
    })
    .join("");
}

// The same wrapper lucide's React component draws, with currentColor inheriting the text color.
const HEAD =
  '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" ' +
  'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">';

const lines = [];
for (const [name, constant] of Object.entries(icons)) {
  const markup = HEAD + readIcon(name) + "</svg>";
  lines.push(
    `/// lucide's \`${name}\`.`,
    `pub const ${constant}: &str = "${markup.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}";`,
    "",
  );
}

const header = `//! The island's icons: lucide's SVG paths, so both shells draw the same glyphs.
//!
//! Generated by \`nsh/scripts/gen-icons.mjs\` from \`lucide-react\`; edit the script, not this
//! file. Each constant is \`<svg>\` markup \`svg()\` draws in the current text color.

`;

writeFileSync(out, header + lines.join("\n"));
console.log(`wrote ${Object.keys(icons).length} icons to ${out}`);
